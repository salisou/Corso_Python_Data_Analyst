-- Restituire la lista di tutti prodotti con il nome della categoria
SELECT 
	p.ProdottoId,
	p.Nome AS 'NOME DEL PRODOTTO',
	c.Nome AS 'NOME DELLA CATEGORIA' 
FROM Prodotto AS p
INNER JOIN Categoria AS c ON p.CategoriaId = C.CategoriaId


