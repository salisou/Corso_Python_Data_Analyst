-- Elenca i prodotti presenti nel Magazzino 1
SELECT 
	p.Nome AS 'Nome del prodotto',
	s.Quantita
FROM STOCK AS s
INNER JOIN Prodotto p ON p.ProdottoId = s.ProdottoId
WHERE MagazzinoId = 1;

-- Restituire i prodotti che hanno una quantità 
-- totale superiore a 200 considerando tutti i magazzini

SELECT 
	p.ProdottoId,
	p.Nome AS 'Nome del prodotto',
	SUM(s.Quantita) AS TotaleMagazzini
FROM STOCK AS s
INNER JOIN Prodotto p ON p.ProdottoId = s.ProdottoId
GROUP BY p.ProdottoId, p.Nome
HAVING SUM(s.Quantita) > 200;


